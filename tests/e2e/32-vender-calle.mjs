// Fase 29: Comprobantes → Vender en la calle. El vendedor baja el paquete, ve su ruta, abre un cliente, arma el pedido y lo manda.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir({ width: 430, height: 900 })
const idle = () => _idle(page); const shot = n => _shot(page, 'calle-' + n)
await _login(page, 'vendedor@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/vender?modo=calle`); await idle()
console.log('  franja:', (await page.innerText('[data-e2e="franja"]')).replace(/\s+/g, ' ').trim())
await page.waitForSelector("[data-e2e^=\"grupo-\"]", { timeout: 20000 }); await page.waitForTimeout(500)
const grupos = await page.locator('[data-e2e^="grupo-"]').allInnerTexts()
console.log('  grupos de la ruta:', grupos.map(g => g.replace(/\s+/g, ' ').trim()).join(' | '))
await shot('01-ruta')
const btn = page.locator('[data-e2e^="venderle-"]').first()
if (!(await btn.isVisible())) await page.locator('[data-e2e^="grupo-"]').first().click()
await page.locator('[data-e2e^="venderle-"]').first().click(); await page.waitForTimeout(800)
console.log('  ficha:', (await page.innerText('[data-e2e="ficha-cliente"]')).replace(/\s+/g, ' ').trim().slice(0, 160))
await shot('02-ficha')
if (await page.locator('[data-e2e="atajo-todo"]').isVisible().catch(() => false)) await page.click('[data-e2e="atajo-todo"]')
const prod = page.locator('[data-e2e^="prod-"]').first(); await prod.locator('input[type=checkbox]').check(); await page.click('[data-e2e="agregar"]')
await page.waitForTimeout(300)
console.log('  total:', (await page.innerText('[data-e2e="total"]')).trim())
await shot('03-pedido')
await page.click('[data-e2e="confirmar"]'); await page.waitForTimeout(1500)
if (await page.locator('[data-e2e="vender-igual"]').isVisible().catch(() => false)) { await page.click('[data-e2e="vender-igual"]'); await page.waitForTimeout(1500) }
console.log('  resultado:', (await page.innerText('[data-e2e="resultado"]')).replace(/\s+/g, ' ').trim())
await shot('04-resultado')
// Cambio de modo: el mismo lugar, pantalla de mostrador.
await page.click('[data-e2e="cambiar-modo"]'); await page.click('[data-e2e="modo-mostrador"]'); await idle(); await page.waitForTimeout(500)
console.log('  modo:', (await page.innerText('[data-e2e="franja"]')).replace(/\s+/g, ' ').trim().slice(0, 60))
await shot('05-mostrador')
await fin(browser)
