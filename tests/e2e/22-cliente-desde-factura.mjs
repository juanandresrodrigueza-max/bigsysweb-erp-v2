// Fase 26.5: cliente nuevo cargado en la misma factura, que queda guardado en Clientes.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'cdf-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/comprobantes/nuevo?tipo=FX`); await idle()
await page.click('[data-e2e="abrir-receptor"]'); await page.waitForTimeout(200)
const dni = String(20000000 + Math.floor(Math.random() * 9000000))
await page.fill('[data-e2e="rc-nombre"]', 'Cliente Mostrador ' + dni)
await page.fill('[data-e2e="rc-doc"]', dni)
await page.click('button:has-text("Agregar")'); await page.waitForTimeout(200)
const art = page.locator('input[placeholder*="Buscar artículo"]').first()
await art.click(); await art.fill('Ladrillo'); await page.waitForTimeout(900)
await page.locator('.shadow-pop button').first().dispatchEvent('mousedown'); await page.waitForTimeout(300)
await shot('01-form')
await page.click('button:has-text("Emitir")'); await idle(); await page.waitForTimeout(1000)
console.log('  emitido:', page.url().includes('/comprobantes/'), '· cliente en el comprobante:', await page.locator(`text=Cliente Mostrador ${dni}`).count() > 0)
const r = await (await page.request.get(`${BASE}/buscar/contactos/cliente?q=${dni}`, { headers: { Accept: 'application/json' } })).json().catch(() => [])
console.log('  quedó en Clientes:', Array.isArray(r) && r.some(c => (c.name || c.label || '').includes(dni)))
await shot('02-emitido')
await fin(browser)
