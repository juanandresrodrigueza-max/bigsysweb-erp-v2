// Fase 25.7: SIFERE en Fiscal, mínimo de stock estadístico y cobrador en el recibo.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'f257-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/contable/fiscal`); await idle()
console.log('  botones SIFERE:', await page.locator('[data-sifere-ret]').count(), await page.locator('[data-sifere-perc]').count(), '· tabla sufridas:', await page.locator('[data-sufridas]').count())
const href = await page.locator('[data-sifere-perc]').getAttribute('href'); const r = await page.request.get(href.startsWith('http') ? href : BASE + href)
console.log('  archivo percepciones:', r.status(), r.headers()['content-disposition'])
await page.locator('[data-sufridas]').scrollIntoViewIfNeeded(); await shot('01-fiscal')
await page.goto(`${BASE}/stock/informes?tipo=minimos`); await idle()
await page.selectOption('[data-metodo]', 'estadistico'); await idle(); await page.waitForTimeout(600)
console.log('  mínimos estadísticos:', await page.locator('tbody tr').count(), 'filas · columna desvío:', await page.locator('th:has-text("Desvío")').count() === 1)
await shot('02-minimos')
// El recibo muestra "Cobró".
await page.goto(`${BASE}/clientes`); await idle()
await page.locator('tbody tr').first().click(); await idle()
await page.click('button:has-text("Registrar cobro")'); await page.waitForTimeout(400)
console.log('  selector de cobrador en el recibo:', await page.locator('[data-cobrador]').count() === 1)
await page.selectOption('.fixed select >> nth=0', 'retencion').catch(() => {})
await page.waitForTimeout(300)
console.log('  retención pide jurisdicción:', await page.locator('[data-retencion-jur]').count() === 1)
await shot('03-recibo')
await fin(browser)
