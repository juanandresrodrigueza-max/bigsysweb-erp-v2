// Fase 26.2: datos por rubro (IVA, tipo, marcas de stock, cuenta de ventas, percepciones) que heredan los artículos.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'rub-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/stock`); await idle()
await page.locator('[class*="btn-ghost"]').filter({ has: page.locator('svg') }).first().click(); await page.waitForTimeout(400)
await page.locator('[data-e2e="editar-rubro"]').first().click(); await page.waitForTimeout(200)
const det = page.locator('[data-e2e="rubro-datos"]')
if (!(await det.evaluate(e => e.open))) await det.locator('summary').click()
await det.locator('select').first().selectOption('10.5')
await page.selectOption('[data-e2e="rubro-control_turno"]', 'true')
await shot('01-rubro')
await page.locator('.fixed button:has-text("Guardar")').first().click(); await idle(); await page.waitForTimeout(600)
await page.locator('[data-e2e="editar-rubro"]').first().click(); await page.waitForTimeout(200)
console.log('  IVA guardado:', await page.locator('[data-e2e="rubro-datos"] select').first().inputValue(), '· se cuenta en el turno:', await page.locator('[data-e2e="rubro-control_turno"]').inputValue())
await page.click('[data-e2e="aplicar-rubro"]'); await idle(); await page.waitForTimeout(600)
console.log('  aviso:', (await page.locator('text=Datos del rubro aplicados').first().innerText().catch(() => '—')).trim())
await shot('02-aplicado')
await fin(browser)
