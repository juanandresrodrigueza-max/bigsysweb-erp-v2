// Fase 25.2: factura manual de talonario cargada con el número del papel.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'manual-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/comprobantes/nuevo?tipo=FX`); await idle()
const cliInput = page.locator('input[placeholder^="Buscar cliente"]').first()
await cliInput.click(); await cliInput.fill('Constructora'); await page.waitForTimeout(900)
await page.locator('.shadow-pop button').first().dispatchEvent('mousedown'); await page.waitForTimeout(600)
await page.check('[data-manual-check]')
await page.fill('[data-pv-manual]', '9'); await page.fill('[data-numero-manual]', String(4000 + Math.floor(Math.random() * 5000)))
await page.fill('input[placeholder="14 dígitos"]', '51234567890123')
await page.click('button:has-text("Agregar")'); await page.waitForTimeout(200)
const art = page.locator('input[placeholder*="Buscar artículo"]').first()
await art.click(); await art.fill('Ladrillo'); await page.waitForTimeout(900)
await page.locator('.shadow-pop button').first().dispatchEvent('mousedown'); await page.waitForTimeout(400)
console.log('  "Informar a ARCA" oculto:', await page.locator('text=Informar a ARCA').count() === 0)
await shot('01-form')
await page.click('button:has-text("Emitir")'); await idle(); await page.waitForTimeout(800)
console.log('  aviso:', (await page.locator('.bg-emerald-50').first().textContent().catch(() => '')).trim().slice(0, 90))
console.log('  badge:', (await page.locator('[data-badge-manual]').textContent().catch(() => '')).trim())
await shot('02-ver')
await fin(browser)
