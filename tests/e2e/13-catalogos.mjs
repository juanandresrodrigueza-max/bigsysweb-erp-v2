// Fase 25.3: catálogo por lista, link público con los colores de la empresa y envío a un cliente.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'catalogo-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/stock`); await idle()
await page.click('[data-ir-catalogos]'); await idle()
await page.click('[data-nuevo-catalogo]'); await page.waitForTimeout(300)
await page.fill('[data-nombre]', 'Lista mayorista'); await page.selectOption('[data-lista]', '2')
await page.fill('textarea', 'Precios válidos por 15 días. Pedido mínimo $ 50.000.')
await page.click('[data-guardar-catalogo]'); await idle(); await page.waitForTimeout(600)
console.log('  catálogos:', await page.locator('[data-catalogo]').count())
await shot('01-lista')
const link = (await page.locator('[data-link]').first().textContent()).trim()
// Mandar a un cliente por WhatsApp (sin API: arma el link).
await page.click('[data-mandar]'); await page.waitForTimeout(300)
const cli = page.locator('[data-cliente-catalogo] input, input[placeholder="Buscar cliente…"]').first()
await cli.click(); await cli.fill('Constructora'); await page.waitForTimeout(900)
await page.locator('.shadow-pop button').first().dispatchEvent('mousedown'); await page.waitForTimeout(300)
await page.fill('input[placeholder="351 555 1234"]', '3515551234')
const [popup] = await Promise.all([page.waitForEvent('popup', { timeout: 5000 }).catch(() => null), page.click('[data-confirmar-envio]')])
await idle(); await page.waitForTimeout(500)
console.log('  whatsapp:', popup ? decodeURIComponent(popup.url()).slice(0, 60) + '…' : 'sin popup', '· aviso:', (await page.locator('.bg-emerald-50').first().textContent().catch(() => '')).trim().slice(0, 50))
if (popup) await popup.close()
// El link público, en celular.
const cel = await browser.newPage({ viewport: { width: 390, height: 844 } })
await cel.goto(link); await cel.waitForTimeout(800)
console.log('  público: artículos', await cel.locator('[data-buscar]').count(), '· rubros', await cel.locator('[data-rubro]').count())
await cel.fill('#q', 'ladrillo'); await cel.waitForTimeout(200)
console.log('  búsqueda "ladrillo":', await cel.locator('[data-buscar]:not([hidden])').count())
await cel.fill('#q', ''); await cel.screenshot({ path: 'tests/e2e/shots/catalogo-02-publico.png' }); console.log('shot catalogo-02-publico')
const pdf = await cel.request.get(link + '/pdf')
console.log('  pdf:', pdf.status(), (await pdf.body()).slice(0, 4).toString())
await cel.close()
await fin(browser)
