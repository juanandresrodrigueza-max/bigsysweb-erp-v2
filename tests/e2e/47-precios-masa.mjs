// Fase 34.1/34.5/34.6: el asistente en tres pasos, la pantalla que salva, cambiar datos en masa, historial y deshacer.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'precios-' + n)
page.on('dialog', d => d.accept())
await _login(page, 'demo@bigsys.com.ar'); await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/stock`); await idle()
await page.click('[data-ir-precios]'); await idle()
console.log('  url:', page.url())
// Paso 2: los que dicen… (texto único por corrida no hay, uso un texto amplio)
await page.click('[data-grupo="texto"]'); await page.fill('[data-e2e="texto"]', 'a'); await page.waitForTimeout(700)
console.log('  cuenta:', (await page.innerText('[data-e2e="cuenta"]')).replace(/\s+/g, ' ').slice(0, 100))
// Paso 3: +5 % lista 1 con aviso si cambia más de 50 %
await page.selectOption('[data-e2e="modo"]', 'porcentaje'); await page.fill('[data-e2e="valor"]', '5')
await page.click('[data-e2e="ver"]'); await page.waitForSelector('[data-e2e="preview"]', { timeout: 15000 })
const prev = (await page.innerText('[data-e2e="preview"] h2')).replace(/\s+/g, ' ')
console.log('  preview:', prev)
await shot('01-preview')
await page.click('[data-e2e="aplicar"]'); await idle(); await page.waitForSelector('[data-e2e="ok"]', { timeout: 15000 })
console.log('  ok:', (await page.innerText('[data-e2e="ok"]')).slice(0, 120))
const hist = (await page.innerText('[data-e2e="historial"]')).replace(/\s+/g, ' ')
console.log('  historial:', hist.slice(0, 140))
await shot('02-grabado')
// Deshacer
await page.click('[data-e2e="historial"] [data-deshacer]'); await idle(); await page.waitForSelector('[data-e2e="ok"]')
console.log('  deshacer:', (await page.innerText('[data-e2e="ok"]')).slice(0, 100))
// Datos en masa: ubicación para los mismos
await page.click('[data-que="datos"]'); await page.waitForTimeout(300)
await page.fill('[data-e2e="ubicacion"]', 'góndola e2e ' + Date.now() % 1000)
await page.click('[data-e2e="ver-datos"]'); await page.waitForSelector('[data-e2e="preview"]', { timeout: 15000 })
console.log('  preview datos:', (await page.innerText('[data-e2e="preview"] h2')).replace(/\s+/g, ' '))
await shot('03-datos')
await page.click('[data-e2e="aplicar"]'); await idle(); await page.waitForSelector('[data-e2e="ok"]', { timeout: 15000 })
console.log('  ok datos:', (await page.innerText('[data-e2e="ok"]')).slice(0, 120))
await page.click('[data-e2e="historial"] [data-deshacer]'); await idle(); await page.waitForSelector('[data-e2e="ok"]')
console.log('  deshacer datos:', (await page.innerText('[data-e2e="ok"]')).slice(0, 100))
await shot('04-final')
await fin(browser)
