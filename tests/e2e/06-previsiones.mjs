// Fase 24.5: previsiones recurrentes y recordatorios para facturar.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'previsiones-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/fondos`); await idle()
console.log('  link previsiones:', await page.locator('a:has-text("Previsiones")').count())
await page.click('a:has-text("Previsiones")'); await idle()
await page.click('button:has-text("Nueva previsión")'); await page.waitForTimeout(300)
await page.fill('.fixed input[placeholder^="Alquiler del local"]', 'Alquiler del local')
await page.locator('.fixed input[type=number]').first().fill('300000')
await page.locator('.fixed select').first().selectOption('3')
await page.click('.fixed button:has-text("Guardar")'); await idle(); await page.waitForTimeout(500)
console.log('  fila:', await page.locator('td:has-text("Alquiler del local")').count(), '· frecuencia:', (await page.locator('tr:has-text("Alquiler del local") td').nth(1).textContent()).trim().slice(0, 14), '· éxito:', (await page.locator('.bg-emerald-50').first().textContent().catch(() => '')).trim().slice(0, 50))
await shot('01-lista')
await page.locator('tr:has-text("Alquiler del local") button:has-text("Registrar")').click(); await page.waitForTimeout(300)
await page.locator('.fixed button:has-text("Registrar")').last().click(); await idle(); await page.waitForTimeout(500)
console.log('  registrado:', (await page.locator('.bg-emerald-50').first().textContent().catch(() => '')).trim().slice(0, 70))
await page.goto(`${BASE}/contable/cashflow`); await idle()
console.log('  fila cash flow:', await page.locator('td:has-text("Previsiones (alquiler")').count())
await shot('02-cashflow')
await fin(browser)
