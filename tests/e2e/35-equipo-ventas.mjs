// Fase 29.6: el encargado publica un aviso; el vendedor lo ve al abrir, anota una nota del cliente y mira su reporte; el equipo en Estadísticas.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page: admin } = await abrir()
await _login(admin, 'demo@bigsys.com.ar'); await admin.click('button:has-text("Saltar")').catch(() => {})
await admin.goto(`${BASE}/clientes/vendedores`); await _idle(admin)
await admin.fill('[data-e2e="aviso-titulo"]', 'Promo galletitas 3x2 toda la semana'); await admin.click('[data-e2e="aviso-publicar"]'); await _idle(admin); await admin.waitForTimeout(500)
console.log('  avisos:', (await admin.innerText('[data-e2e="avisos"]')).replace(/\s+/g, ' ').trim().slice(0, 140))
const ctx = await browser.newContext({ viewport: { width: 430, height: 900 } }); const page = await ctx.newPage()
const idle = () => _idle(page); const shot = n => _shot(page, 'equipo-' + n)
await _login(page, 'vendedor@bigsys.com.ar'); await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/vender?modo=calle`); await idle()
console.log('  aviso en la app:', (await page.locator('[data-e2e^="aviso-"]').first().innerText()).replace(/\s+/g, ' ').trim())
await page.waitForSelector('[data-e2e^="grupo-"]', { timeout: 20000 })
if (!(await page.locator('[data-e2e^="venderle-"]').first().isVisible())) await page.locator('[data-e2e^="grupo-"]').first().click()
await page.locator('[data-e2e^="venderle-"]').first().click(); await page.waitForTimeout(800)
await page.fill('[data-e2e="nota-texto"]', 'Prefiere entrega los martes'); await page.click('[data-e2e="nota-guardar"]'); await page.waitForTimeout(800)
console.log('  nota:', (await page.locator('[data-e2e^="nota-"]').nth(0).innerText()).replace(/\s+/g, ' ').trim().slice(0, 80))
await shot('01-nota')
await page.click('[data-e2e="ir-reporte"]'); await page.waitForTimeout(1200)
console.log('  reporte:', (await page.innerText('[data-e2e="pantalla-reporte"]')).replace(/\s+/g, ' ').trim().slice(0, 300))
await shot('02-reporte')
await admin.goto(`${BASE}/estadisticas/vendedores?periodo=mes`); await _idle(admin)
console.log('  ranking:', (await admin.innerText('[data-e2e="ranking"]')).replace(/\s+/g, ' ').trim().slice(0, 200))
console.log('  ruta:', (await admin.innerText('[data-e2e="ruta"]')).replace(/\s+/g, ' ').trim().slice(0, 200))
await _shot(admin, 'equipo-03-encargado')
await fin(browser)
