// Fase 32.1: la caja fluida: frecuentes, dejar una venta en espera y retomarla, DNI del consumidor final, últimas ventas, anular la última y una devolución.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'caja-' + n)
page.on('dialog', d => d.accept(d.type() === 'prompt' ? (d.message().includes('llamamos') ? 'el del gorro' : 'se equivocó') : undefined))
await _login(page, 'demo@bigsys.com.ar'); await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/retail`); await idle(); await page.waitForTimeout(500)
console.log('  chip frecuentes:', await page.locator('[data-e2e="chip-frecuentes"]').isVisible().catch(() => false))
// armo una venta y la dejo en espera
await page.fill('input[placeholder^="Código de barras"]', 'cemento'); await page.waitForTimeout(400); await page.keyboard.press('Enter'); await page.waitForTimeout(300)
console.log('  total:', await page.innerText('[data-e2e="total"]'))
await page.click('[data-e2e="dejar-espera"]'); await page.waitForTimeout(300)
console.log('  en espera:', await page.innerText('[data-e2e="espera-0"]'), '· ticket vacío:', (await page.innerText('body')).includes('Ticket vacío'))
await shot('01-en-espera')
// otra venta con DNI y cheque + efectivo
await page.fill('input[placeholder^="Código de barras"]', 'hierro'); await page.waitForTimeout(400); await page.keyboard.press('Enter'); await page.waitForTimeout(300)
await page.keyboard.press('F9'); await page.waitForTimeout(400)
await page.fill('[data-e2e="dni"] input >> nth=0', '30123456'); await page.fill('[data-e2e="dni"] input >> nth=1', 'Juan Pérez')
await page.click('button:has-text("Cheque")'); await page.waitForTimeout(200)
await page.fill('[data-e2e="cheque-datos"] input >> nth=0', '1001'); await page.selectOption('[data-e2e="cheque-datos"] select', { index: 1 }); await page.fill('[data-e2e="cheque-datos"] input[type=date]', '2026-12-10')
await shot('02-cobro-cheque')
await page.click('button:has-text("Confirmar y emitir")'); await idle(); await page.waitForTimeout(800)
const ok = (await page.innerText('body')).match(/Venta\s+\S+\s+por/)?.[0]; console.log('  vendida:', ok)
// retomo la que estaba en espera
await page.click('[data-e2e="espera-0"]'); await page.waitForTimeout(300)
console.log('  retomada total:', await page.innerText('[data-e2e="total"]'), '· quedan en espera:', await page.locator('[data-e2e^="espera-"]').count())
await page.keyboard.press('F9'); await page.waitForTimeout(300); await page.click('button:has-text("Confirmar y emitir")'); await idle(); await page.waitForTimeout(800)
// últimas ventas: anular la última, devolver una de la anterior
await page.click('[data-e2e="ultimas"]'); await page.waitForTimeout(800)
const filas = await page.locator('[data-e2e^="ultima-"]').count(); console.log('  últimas:', filas)
await shot('03-ultimas')
await page.locator('[data-e2e^="anular-"]').first().click(); await page.waitForTimeout(1200)
console.log('  anular:', await page.innerText('[data-e2e="msj-ultimas"]'))
await page.locator('[data-e2e^="ultima-"]').nth(1).locator('button:has-text("Devolución")').click(); await page.waitForTimeout(300)
await page.locator('.fixed.inset-0 input[type=checkbox]').last().check(); await page.waitForTimeout(100)
await shot('04-devolucion')
await page.click('[data-e2e="confirmar-devolucion"]'); await page.waitForTimeout(1500)
console.log('  devolución:', await page.innerText('[data-e2e="msj-ultimas"]'))
await shot('05-despues')
await fin(browser)
