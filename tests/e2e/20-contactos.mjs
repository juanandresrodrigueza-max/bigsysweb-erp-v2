// Fase 26.3: personas de contacto en la ficha del cliente y sugeridas al enviar.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'con-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/clientes`); await idle()
await page.locator('tbody tr').first().click(); await idle()
await page.click('button:has-text("Contactos")'); await page.waitForTimeout(600)
const box = page.locator('[data-e2e="personas"]')
await box.locator('button:has-text("Agregar contacto")').click()
const inputs = box.locator('input:not([type=checkbox])')
await inputs.nth(0).fill('Luis Tesorería'); await inputs.nth(1).fill('Pagos'); await inputs.nth(2).fill('2615551234'); await inputs.nth(3).fill('luis.pagos@ejemplo.com')
await box.locator('label:has-text("Recibe recibos") input').check()
await box.locator('button:has-text("Guardar")').click(); await page.waitForTimeout(800)
console.log('  contacto cargado:', await box.locator('text=Luis Tesorería').count() >= 1)
await shot('01-contactos')
await page.click('button:has-text("Enviar resumen")'); await page.waitForTimeout(1200)
console.log('  sugerido en el envío:', await page.locator('[data-e2e="personas-envio"] button:has-text("Luis Tesorería")').count() >= 1, '· destino:', await page.locator('.fixed input.input').first().inputValue())
await shot('02-envio')
await fin(browser)
