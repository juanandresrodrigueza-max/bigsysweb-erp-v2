// Fase 36.2/36.5/36.6: recepción con checklist y daños, acta PDF, que vuelva, historia, para revisar y que vuelvan.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'historia-' + n)
await _login(page, 'demo@bigsys.com.ar'); await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/servicios`); await idle()
console.log('  para revisar:', await page.locator('[data-e2e="para-revisar"] a').count())
const primera = page.locator('a[href^="/servicios/"][href$="0"], a[href^="/servicios/"]').filter({ hasText: 'OT-' }).first()
await primera.click(); await idle()
await page.locator('[data-e2e="recepcion"] button[title="rojo"]').first().click()
await page.click('[data-e2e="recepcion"] button:has-text("+ daño")'); await page.locator('[data-e2e="recepcion"] input[placeholder="Zona"]').last().fill('Puerta e2e'); await page.locator('[data-e2e="recepcion"] input[placeholder="Qué tiene"]').last().fill('Rayón')
await page.click('[data-e2e="guardar-recepcion"]'); await idle(); await page.waitForTimeout(400)
console.log('  recepción guardada:', (await page.innerText('[data-e2e="recepcion"]')).includes('Puerta e2e') || await page.locator('[data-e2e="recepcion"] input[placeholder="Zona"]').last().inputValue())
const acta = await page.request.get(page.url() + '/acta'); console.log('  acta:', acta.status(), acta.headers()['content-type'])
await page.fill('[data-e2e="vuelta"] input >> nth=0', '6'); await page.click('[data-e2e="vuelta"] button:has-text("Agendar")'); await idle(); await page.waitForTimeout(300)
console.log('  vuelta:', (await page.innerText('[data-e2e="vuelta"]')).replace(/\s+/g, ' ').slice(-60))
await shot('01-orden')
await page.goto(`${BASE}/servicios/que-vuelvan?dias=200`); await idle()
console.log('  que vuelvan:', (await page.innerText('[data-e2e="lista"]')).replace(/\s+/g, ' ').slice(0, 140))
await shot('02-que-vuelvan')
await fin(browser)
