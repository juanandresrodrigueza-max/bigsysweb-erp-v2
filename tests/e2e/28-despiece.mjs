// Fase 27.3: carnicería: plantilla de despiece, despiece con rinde y costo por corte, y factura leyendo la etiqueta de la balanza.
import { execSync } from 'node:child_process'
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const t = Date.now().toString().slice(-5)
const ids = execSync(`php artisan tinker --execute 'auth()->login(App\\Models\\User::where("email","demo@bigsys.com.ar")->first()); $b=auth()->user()->business_id; $mk=fn($n,$pr,$c,$ex=[])=>App\\Models\\Product::create(array_merge(["business_id"=>$b,"name"=>$n." ${t}","sku"=>strtoupper(substr($n,0,3))."${t}","tipo"=>"producto","unit"=>"kg","price"=>$pr,"cost"=>$c,"iva"=>10.5,"controla_stock"=>true,"active"=>true],$ex)); $m=$mk("Media res",0,4000); app(App\\Services\\Stock\\StockService::class)->entrada($m,200,"e2e",null,null,4000); $a=$mk("Asado",9000,0,["pesable"=>true,"plu"=>"${t}"]); $n=$mk("Nalga",12000,0); echo $m->id.",".$a->id.",".$n->id;'`).toString().trim().split('\n').pop().split(',')
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'desp-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/stock/despiece`); await idle()
await page.click('[data-e2e="tab-plantillas"]')
const f = page.locator('[data-e2e="form-plantilla"]')
await f.locator('input').first().fill('Media res e2e ' + t)
await f.locator('select').first().selectOption(ids[0])
await f.locator('select').nth(1).selectOption(ids[1]); await f.locator('input[type=number]').first().fill('20')
await f.locator('button:has-text("+ Agregar corte")').click()
await f.locator('select').nth(2).selectOption(ids[2]); await f.locator('input[type=number]').nth(1).fill('15')
await f.locator('button:has-text("Guardar")').click(); await idle(); await page.waitForTimeout(700)
await page.click('[data-e2e="tab-despiece"]')
const dz = page.locator('[data-e2e="form-despiece"]')
await dz.locator('select').first().selectOption({ label: new RegExp(`Media res e2e ${t}`) }).catch(async () => { const v = await dz.locator('select option', { hasText: 'Media res e2e ' + t }).getAttribute('value'); await dz.locator('select').first().selectOption(v) })
await page.fill('[data-e2e="kg-entrada"]', '100')
await page.fill(`[data-e2e="corte-${ids[1]}"]`, '19'); await page.fill(`[data-e2e="corte-${ids[2]}"]`, '16')
await shot('01-despiece')
await page.click('[data-e2e="registrar-despiece"]'); await idle(); await page.waitForTimeout(900)
const op = page.locator('[data-e2e="operacion"]').first()
console.log('  despiece registrado:', (await op.locator('p').first().innerText()).trim(), '·', (await op.locator('p').nth(1).innerText()).trim())
await shot('02-resultado')
// Factura leyendo una etiqueta de balanza del asado: 2 + PLU + 1,250 kg.
await page.goto(`${BASE}/comprobantes/nuevo?tipo=FX`); await idle()
await page.fill('[data-e2e="scan-factura"]', `2${t.padStart(5, '0')}01250` + '00'); await page.press('[data-e2e="scan-factura"]', 'Enter'); await page.waitForTimeout(1200)
console.log('  línea desde la balanza, cantidad:', await page.locator('[data-cant="0"]').inputValue().catch(() => '—'))
await shot('03-factura')
await fin(browser)
