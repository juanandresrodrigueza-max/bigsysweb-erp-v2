// Fase 24.4: sucursal con CUIT propio y consolidado de casa central.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'sucursales-' + n)
await _login(page, 'demo@bigsys.com.ar')
await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/configuracion/sucursales`); await idle()
await page.click('button:has-text("Nueva sucursal")'); await page.waitForTimeout(300)
await page.fill('.fixed input.input >> nth=0', 'Sucursal Rosario ' + (Date.now() % 1000))
await page.locator('.fixed label:has-text("Factura con su propio CUIT") input').check(); await page.waitForTimeout(200)
console.log('  campos CUIT propio:', await page.locator('.fixed label:has-text("Razón social")').count(), await page.locator('.fixed label:has-text("Inicio de actividades")').count())
await page.fill('.fixed input[placeholder="30-12345678-9"]', '30-99999999-3')
await page.click('.fixed button:has-text("Guardar")'); await idle(); await page.waitForTimeout(400)
console.log('  error razón social:', await page.locator('.fixed :text("cargá su razón social")').count())
await page.locator('.fixed label:has-text("Razón social") + input').fill('Rosario Sur SA')
await page.click('.fixed button:has-text("Guardar")'); await idle(); await page.waitForTimeout(500)
console.log('  badge CUIT propio:', await page.locator('.badge:has-text("CUIT propio")').count(), '· aviso certificado:', await page.locator('text=Falta el certificado ARCA').count(), '· botón cert:', await page.locator('button:has-text("Certificado ARCA")').count())
await shot('01-sucursal-cuit')
await page.locator('button:has-text("Certificado ARCA")').first().click(); await page.waitForTimeout(300)
console.log('  modal cert:', await page.locator('.fixed :text("30-99999999-3")').count())
await page.keyboard.press('Escape'); await page.waitForTimeout(200)
// Consolidado desde el selector de sucursal
await page.goto(`${BASE}/dashboard`); await idle()
await page.locator('[data-tour="sucursal"] button').click(); await page.waitForTimeout(300)
console.log('  opción consolidado:', await page.locator('button:has-text("Ver consolidado de todas")').count())
await page.click('button:has-text("Ver consolidado de todas")'); await idle(); await page.waitForTimeout(600)
console.log('  subtítulo:', (await page.locator('p.page-subtitle').first().textContent()).trim().slice(0, 80), '· badge:', await page.locator('.badge:has-text("consolidado")').count())
await shot('02-consolidado')
await page.locator('[data-tour="sucursal"] button').click(); await page.waitForTimeout(300); await page.click('button:has-text("Ver consolidado de todas")'); await idle()
await fin(browser)
