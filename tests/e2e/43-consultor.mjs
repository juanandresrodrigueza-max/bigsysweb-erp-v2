// Fase 32.4–32.5: el Consultor de precios: buscar, la ficha con costo y margen (dueño), el simulador, la cotización, y la pantalla del salón con su llave.
import { abrir, idle as _idle, shot as _shot, login as _login, fin, BASE } from './lib.mjs'
const { browser, ctx, page } = await abrir()
const idle = () => _idle(page); const shot = n => _shot(page, 'consultor-' + n)
page.on('dialog', d => d.accept())
await _login(page, 'demo@bigsys.com.ar'); await page.click('button:has-text("Saltar")').catch(() => {})
await page.goto(`${BASE}/stock/consultor`); await idle()
await page.fill('[data-e2e="buscador"]', 'cemento'); await page.waitForTimeout(700)
console.log('  resultados:', await page.locator('[data-e2e^="res-"]').count())
await shot('01-busqueda')
await page.keyboard.press('Enter'); await page.waitForTimeout(800)
console.log('  ficha:', (await page.innerText('[data-e2e="ficha"]')).replace(/\s+/g, ' ').slice(0, 120))
console.log('  costo visible (dueño):', await page.locator('[data-e2e="costo"]').isVisible(), '· proveedores:', await page.locator('[data-e2e="proveedores"]').isVisible())
await shot('02-ficha')
await page.fill('[data-e2e="ficha"] input[type=number]', '3'); await page.click('[data-e2e="al-simulador"]'); await page.waitForTimeout(400)
console.log('  simulador total:', await page.innerText('[data-e2e="sim-total"]'))
// 2*código de barras entra directo
await page.fill('[data-e2e="buscador"]', '2*7790001000028'); await page.keyboard.press('Enter'); await page.waitForTimeout(900)
console.log('  renglones:', await page.locator('[data-e2e^="sim-"]').count(), '· total:', await page.innerText('[data-e2e="sim-total"]'))
// Costo y margen como una lista más
await page.selectOption('[data-e2e="lista"]', '0'); await page.fill('[data-e2e="buscador"]', 'hierro'); await page.waitForTimeout(700)
console.log('  modo costo:', (await page.innerText('[data-e2e^="res-"] >> nth=0')).replace(/\s+/g, ' ').slice(0, 120))
await page.selectOption('[data-e2e="lista"]', '1')
await shot('03-simulador')
// la cotización (PDF en otra pestaña)
const [pdf] = await Promise.all([ctx.waitForEvent('page'), page.click('button:has-text("Imprimir / PDF")')])
await pdf.waitForLoadState('load').catch(() => {}); console.log('  pdf abierto:', pdf.url().includes('/q/'), '· guardada:', await page.locator('[data-e2e="cot-ok"]').isVisible())
// pantalla del salón
await page.click('[data-e2e="pantallas"]'); await page.waitForTimeout(300)
await page.fill('[data-e2e="pantalla-nombre"]', 'Góndola e2e')
const [salon] = await Promise.all([ctx.waitForEvent('page'), page.click('[data-e2e="pantalla-crear"]')])
await salon.waitForLoadState('networkidle'); await salon.waitForTimeout(1200)
console.log('  salón:', salon.url().includes('/salon/'), '·', (await salon.innerText('#estado')).slice(0, 60))
await salon.evaluate(() => window.leerSalon('7790001000011')); await salon.waitForTimeout(400)
console.log('  salón muestra:', (await salon.innerText('#main')).replace(/\s+/g, ' ').slice(0, 100))
await _shot(salon, 'consultor-04-salon')
// sin login también anda (es la llave de la pantalla)
const ctx2 = await browser.newContext(); const anon = await ctx2.newPage(); const r = await anon.goto(salon.url()); console.log('  salón sin login:', r.status())
await fin(browser)
